import re, sys, collections
D = sys.argv[1]
def ranges(path, want=None, field=1):
    out = {}
    for line in open(f"{D}/{path}", encoding="utf-8"):
        line = line.split('#')[0].strip()
        if not line: continue
        parts = [p.strip() for p in line.split(';')]
        cp, val = parts[0], parts[field]
        a, b = (cp.split('..') + [cp])[:2] if '..' in cp else (cp, cp)
        if want is None or val in want:
            for c in range(int(a,16), int(b,16)+1): out[c] = val
    return out
WB = ranges("WordBreakProperty.txt")
SA = ranges("LineBreak.txt", {"SA"})
SC = ranges("Scripts.txt", {"Han", "Hiragana"})
# Nd in the Halfwidth and Fullwidth Forms block
hf = None
for line in open(f"{D}/Blocks.txt"):
    if "Halfwidth and Fullwidth Forms" in line:
        a, b = line.split(';')[0].split('..'); hf = (int(a,16), int(b,16))
nd = set()
for line in open(f"{D}/UnicodeData.txt"):
    f = line.split(';')
    if f[2] == "Nd": nd.add(int(f[0],16))
CLS = {"ALetter":1,"Hebrew_Letter":2,"Numeric":3,"Katakana":4,"ExtendNumLet":5,"MidLetter":6,"MidNum":7,"MidNumLet":8,"Single_Quote":9,"Double_Quote":10,"Format":11,"Extend":11,"Regional_Indicator":12}
val = {}
over = collections.Counter()
for c in range(0x110000):
    v = CLS.get(WB.get(c), 0)
    if v == 0 and hf[0] <= c <= hf[1] and c in nd: v = 3
    if c in SA: v |= 0x10; over["SA&"+str(v & 15)] += 1
    s = SC.get(c)
    if s == "Han": v |= 0x20; over["Han&"+str(v & 15)] += 1
    if s == "Hiragana": v |= 0x40; over["Hira&"+str(v & 15)] += 1
    if v: val[c] = v
print(dict(over), file=sys.stderr)
runs = []
for c in sorted(val):
    if runs and runs[-1][1] == c-1 and runs[-1][2] == val[c]: runs[-1][1] = c
    else: runs.append([c, c, val[c]])
print(len(runs), "runs", file=sys.stderr)
o = []
o.append("// <auto-generated>")
o.append("// Generated from the Unicode Character Database 6.3.0 (WordBreakProperty.txt, LineBreak.txt,")
o.append("// Scripts.txt, Blocks.txt, UnicodeData.txt), the version the previous Lucene 4.8 analysis used.")
o.append("// Each entry: first code point, last code point, class (low 4 bits: word-break class, see WordBreakData;")
o.append("// 0x10 Line_Break=Complex_Context; 0x20 Script=Han; 0x40 Script=Hiragana).")
o.append("// </auto-generated>")
o.append("namespace PhoenixmlDb.XQuery.FullText;")
o.append("")
o.append("internal static partial class WordBreakData")
o.append("{")
o.append("    private static readonly int[] RangeData =")
o.append("    [")
line = "       "
for a,b,v in runs:
    item = f" 0x{a:X},0x{b:X},{v},"
    if len(line) + len(item) > 110: o.append(line); line = "       "
    line += item
o.append(line)
o.append("    ];")
o.append("}")
open(sys.argv[2], "w").write("\n".join(o) + "\n")
